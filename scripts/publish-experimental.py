"""Publish only the generated updates branch. This script never creates releases/tags."""
import os,json,base64,hashlib,urllib.request,urllib.error
from pathlib import Path
REPO='MrHaydenn/Anti-Spoiler-Esports---Android-TV'
if os.environ.get('GITHUB_REPOSITORY')!=REPO:raise SystemExit('Unexpected repository')
token=os.environ['GITHUB_TOKEN']
def api(path,method='GET',data=None,missing=False):
    request=urllib.request.Request('https://api.github.com/repos/'+REPO+path,method=method,data=None if data is None else json.dumps(data).encode(),headers={'Authorization':'Bearer '+token,'Accept':'application/vnd.github+json','User-Agent':'Anti-Spoiler-Esports-TV-build','X-GitHub-Api-Version':'2022-11-28'})
    try:
        with urllib.request.urlopen(request,timeout=60) as response:return json.load(response)
    except urllib.error.HTTPError as error:
        if missing and error.code==404:return None
        raise SystemExit('Experimental publishing failed: HTTP '+str(error.code))
manifest=json.loads(Path('dist/update.json').read_text());apk=Path('dist/anti-spoiler-esports-tv.apk').read_bytes()
if manifest['channel']!='experimental' or hashlib.sha256(apk).hexdigest()!=manifest['sha256']:raise SystemExit('Invalid experimental artifact')
previous=api('/contents/experimental/update.json?ref=updates',missing=True)
if previous:
    old=json.loads(base64.b64decode(previous['content']))
    if old['versionCode']>=manifest['versionCode']:raise SystemExit('A newer experimental update already exists; leaving it in place.')
ref=api('/git/ref/heads/updates',missing=True);parents=[];base=None
if ref:
    sha=ref['object']['sha'];parents=[sha];base=api('/git/commits/'+sha)['tree']['sha']
blob=api('/git/blobs','POST',{'encoding':'base64','content':base64.b64encode(apk).decode()})
entries=[{'path':'experimental/anti-spoiler-esports-tv.apk','mode':'100644','type':'blob','sha':blob['sha']},{'path':'experimental/update.json','mode':'100644','type':'blob','content':json.dumps(manifest,indent=2)+'\n'},{'path':'README.md','mode':'100644','type':'blob','content':'# Experimental Android TV update feed\n\nGenerated by push builds. These files are not GitHub Releases. Source is on main; stable-source snapshots are on release.\n'}]
tree_data={'tree':entries}
if base:tree_data['base_tree']=base
tree=api('/git/trees','POST',tree_data)
commit=api('/git/commits','POST',{'message':'Experimental Android TV '+manifest['versionName'],'tree':tree['sha'],'parents':parents})
if ref:api('/git/refs/heads/updates','PATCH',{'sha':commit['sha'],'force':False})
else:api('/git/refs','POST',{'ref':'refs/heads/updates','sha':commit['sha']})
print('Experimental feed updated. No tags, prereleases or GitHub Releases were created.')
